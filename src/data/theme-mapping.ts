// Fonction pour migrer un tableau de thèmes
export function migrateThemes(oldThemes: string[]): string[] {
  const migrated: string[] = [];
  const seen = new Set<string>();
  
  for (const oldTheme of oldThemes) {
    const normalized = oldTheme.toLowerCase().trim();
    const newTheme = THEME_MIGRATION_MAP[normalized];
    
    if (newTheme && !seen.has(newTheme)) {
      migrated.push(newTheme);
      seen.add(newTheme);
    } else if (!newTheme && !seen.has(normalized)) {
      // Garde le thème original si pas de mapping
      // Mais normalise-le
      migrated.push(normalized);
      seen.add(normalized);
    }
  }
  
  return migrated;
}

